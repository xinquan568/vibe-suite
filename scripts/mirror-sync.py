"""Mirror-sync generator (E7.2 / vibe-54, F9.6).

Regenerates the Codex CLI mirror under ``codex/`` from four source sets and writes
``codex/MIRROR-MANIFEST.json`` — per-FILE records binding every mirror file to the exact
source bytes it was generated from, plus reasoned rows for everything deliberately not
mirrored. ``bin/vibe-check --mirrors`` is the independent reader.

Determinism is a contract (the acceptance says byte-identical): sorted iteration, no
timestamps, version read only from the plugin manifest, stable JSON.

Inventory comes from the PRODUCTION TABLES below. The only injection point is the
``sets=`` parameter of :func:`generate` — a Python-API seam for unit tests; the CLI is
unconditionally production-bound (no flag, no environment variable — pinned by
``tests/test_mirror_sync.py::ProductionBinding``).
"""

